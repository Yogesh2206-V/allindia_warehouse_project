/**
 * Smart Locality & City Search Engine
 * Matches any letter from A to Z across all cities and localities.
 * Supports:
 * - Single letter searches (e.g. typing 'A' lists all 'A' starting localities/cities)
 * - Prefix & substring matching
 * - Acronyms ('MGR', 'SIPCOT', 'MIDC', 'GIDC', 'NH48')
 */
export function searchLocalitiesInCity(cityName, query = '') {
  const cityData = CITY_LOCALITIES_DATABASE[cityName] || CITY_LOCALITIES_DATABASE["Chennai"];
  const cleanCity = cityName || "Chennai";
  const state = cityData?.state || "Tamil Nadu";
  const allList = cityData?.localities || [];

  if (!query || query.trim() === '') {
    // Return sorted alphabetical localities by default
    return allList.slice(0, 10).map(loc => ({
      name: loc.name,
      formatted: `${loc.name}, ${cleanCity}, ${state}, India`,
      city: cleanCity,
      state: state
    }));
  }

  const q = query.toLowerCase().trim();
  const qCompact = q.replace(/[^a-z0-9]/g, '');
  const isSingleLetter = q.length === 1;

  const matches = allList.filter(loc => {
    const nameLower = loc.name.toLowerCase();
    const words = nameLower.split(/[\s,/-]+/).filter(Boolean);

    // 1. If single letter query (e.g. 'b', 'a', 'c') -> STRICT: only items where the name or word starts with that letter
    if (isSingleLetter) {
      return nameLower.startsWith(q) || words.some(w => w.startsWith(q));
    }

    // 2. Exact prefix match with query or word-level prefix match
    if (nameLower.startsWith(q) || words.some(w => w.startsWith(q))) return true;

    // 3. Tag match (e.g. 'mgr', 'sipcot', 'airport', 'sez', 'nh48', 'omr', 'ecr')
    if (loc.tags && loc.tags.some(t => {
      const tLower = t.toLowerCase();
      return tLower === q || tLower === qCompact || tLower.startsWith(q);
    })) {
      return true;
    }

    // 4. Initials acronym match (e.g. 'MGR' -> MGR Nagar, 'MWC' -> Mahindra World City)
    if (qCompact.length >= 2 && qCompact.length <= 4) {
      const initials = words.map(w => w[0]).join('');
      if (initials.startsWith(qCompact)) return true;
    }

    // 5. Substring match if 3+ characters (e.g. 'park', 'corridor', 'estate')
    if (q.length >= 3 && nameLower.includes(q)) return true;

    return false;
  });

  // Sort: starting with letter/query first, then alphabetical
  matches.sort((a, b) => {
    const aLower = a.name.toLowerCase();
    const bLower = b.name.toLowerCase();
    const aStarts = aLower.startsWith(q);
    const bStarts = bLower.startsWith(q);
    if (aStarts && !bStarts) return -1;
    if (!aStarts && bStarts) return 1;
    return aLower.localeCompare(bLower);
  });

  return matches.map(loc => ({
    name: loc.name,
    formatted: `${loc.name}, ${cleanCity}, ${state}, India`,
    city: cleanCity,
    state: state
  }));
}

/**
 * Global A-to-Z City Search Function
 * Matches any letter from A to Z across all cities in India.
 */
export function searchCitiesAZ(query = '') {
  if (!query || query.trim() === '') {
    return ALL_INDIAN_CITIES_AZ;
  }
  const q = query.toLowerCase().trim();
  if (q.length === 1) {
    return ALL_INDIAN_CITIES_AZ.filter(c => c.name.toLowerCase().startsWith(q));
  }
  return ALL_INDIAN_CITIES_AZ.filter(c => 
    c.name.toLowerCase().startsWith(q) || 
    c.name.toLowerCase().includes(q) ||
    c.state.toLowerCase().startsWith(q)
  );
}
